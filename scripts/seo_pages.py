def write_style_pages(site_dir: Path, styles: list[dict[str, Any]]) -> None:
    pages_dir = site_dir / "styles"
    pages_dir.mkdir(exist_ok=True)
    keep = {s["slug"] for s in styles}
    for child in pages_dir.iterdir():
        if child.is_dir() and child.name not in keep:
            shutil.rmtree(child)
    for style in styles:
        out = pages_dir / style["slug"] / "index.html"
        out.parent.mkdir(exist_ok=True)
        out.write_text(style_page(style, styles), encoding="utf-8")


def write_sitemap(root: Path, styles: list[dict[str, Any]]) -> None:
    urls = [f"{BASE_URL}/site/"] + [page_url(s["slug"]) for s in styles]
    body = "\n".join(f"  <url><loc>{esc(u)}</loc></url>" for u in urls)
    (root / "sitemap.xml").write_text(
        '<?xml version="1.0" encoding="UTF-8"?>\n'
        '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n'
        f"{body}\n</urlset>\n",
        encoding="utf-8",
    )


def write_llms_txt(root: Path, styles: list[dict[str, Any]], categories: list[str]) -> None:
    lines = [
        "# AI Visual Prompt Cookbook",
        "",
        f"> {len(styles)} plug-and-play visual style packs for AI image generation ({MODELS}, ChatGPT, Gemini, Claude).",
        "> Each style is one structured style.json: paste it into an LLM image workflow, replace the variables, keep the look.",
        "",
        f"Curated by {AUTHOR} ({AUTHOR_URL}). Source: {REPO_URL}",
        "",
        "## How to use a style",
        "",
        "1. Pick a style below and open its page, or fetch its raw style.json.",
        "2. Paste the whole JSON into the chat or image workflow.",
        "3. Replace the values in `environment_variables` (subject, headline text, aspect ratio...) and generate.",
        "",
        f"- [Online gallery]({BASE_URL}/site/): searchable previews of every style",
        f"- [Catalog]({REPO_URL}/blob/main/docs/CATALOG.md): full list with categories",
        "",
    ]
    for category in categories:
        lines += [f"## {category}", ""]
        for s in styles:
            if s["category"] == category:
                lines.append(
                    f"- [{s['name']}]({page_url(s['slug'])}): {clip(s['description'], 220)} "
                    f"Raw JSON: {BASE_URL}/styles/{s['slug']}/style.json"
                )
        lines.append("")
    (root / "llms.txt").write_text("\n".join(lines), encoding="utf-8")


def inject_index(index_html: Path, styles: list[dict[str, Any]], categories: list[str]) -> None:
    text = index_html.read_text(encoding="utf-8")
    if INDEX_START not in text or INDEX_END not in text:
        raise ValueError(f"{index_html} is missing the STYLE-INDEX markers")
    groups = []
    for category in categories:
        links = "\n".join(
            f'            <li><a href="styles/{esc(s["slug"])}/">{esc(s["name"])}</a></li>'
            for s in styles
            if s["category"] == category
        )
        groups.append(
            f"""        <div class="index-group">
          <h3>{esc(category)}</h3>
          <ul>
{links}
          </ul>
        </div>"""
        )
    block = f"{INDEX_START}\n" + "\n".join(groups) + f"\n        {INDEX_END}"
    pattern = re.escape(INDEX_START) + r".*?" + re.escape(INDEX_END)
    index_html.write_text(re.sub(pattern, lambda _: block, text, flags=re.DOTALL), encoding="utf-8")


def build_all(root: Path, site_dir: Path, styles: list[dict[str, Any]], categories: list[str]) -> None:
    write_style_pages(site_dir, styles)
    write_sitemap(root, styles)
    write_llms_txt(root, styles, categories)
    inject_index(site_dir / "index.html", styles, categories)
