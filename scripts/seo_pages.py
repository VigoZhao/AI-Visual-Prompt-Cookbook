"""Static, crawlable outputs for the style browser.

Called by build-pages-mvp.py. Writes one HTML page per style under
site/styles/<slug>/, plus sitemap.xml, llms.txt and a plain-link style index
injected into site/index.html. Everything here is derived from the same style
list as site/styles-data.js, so it stays in sync on every build.
"""

from __future__ import annotations

import html
import json
import re
import shutil
from pathlib import Path
from typing import Any

BASE_URL = "https://prompts.vigocreativeai.com"
REPO_URL = "https://github.com/VigoZhao/AI-Visual-Prompt-Cookbook"
AUTHOR = "Vigo Zhao"
AUTHOR_URL = "https://x.com/VigoCreativeAI"
MODELS = "Nano Banana Pro, GPT Image, Midjourney"

# Cloudflare Web Analytics beacon for prompts.vigocreativeai.com (the token is public by design).
ANALYTICS = (
    "<!-- Cloudflare Web Analytics --><script type='module' src='https://static.cloudflareinsights.com/beacon.min.js' "
    "data-cf-beacon='{\"token\": \"8aeae43b7eea4bf991a493b61ca89f1a\"}'></script><!-- End Cloudflare Web Analytics -->"
)

INDEX_START = "<!-- STYLE-INDEX:START (generated by scripts/build-pages-mvp.py) -->"
INDEX_END = "<!-- STYLE-INDEX:END -->"

esc = html.escape
ANCHOR_TAG = re.compile(r"^\[[A-Z]+\]\s*")


def clip(text: str, limit: int = 155) -> str:
    text = re.sub(r"\s+", " ", text).strip()
    if len(text) <= limit:
        return text
    return text[: limit - 1].rsplit(" ", 1)[0].rstrip(",;:—-") + "…"


def page_url(slug: str) -> str:
    return f"{BASE_URL}/site/styles/{slug}/"


def label_for(key: str) -> str:
    return key.replace("_", " ").lower()


def json_ld(style: dict[str, Any]) -> str:
    url = page_url(style["slug"])
    data = [
        {
            "@context": "https://schema.org",
            "@type": "CreativeWork",
            "name": f"{style['name']} — AI image style prompt",
            "description": style["description"],
            "url": url,
            "image": [
                f"{BASE_URL}/styles/{style['slug']}/preview-16x9.jpg",
                f"{BASE_URL}/styles/{style['slug']}/preview-9x16.jpg",
            ],
            "genre": style["category"],
            "keywords": f"{style['name']}, {style['category']}, AI image prompt, style.json, {MODELS}",
            "encodingFormat": "application/json",
            "author": {"@type": "Person", "name": AUTHOR, "url": AUTHOR_URL},
            "isPartOf": {"@type": "Collection", "name": "AI Visual Prompt Cookbook", "url": f"{BASE_URL}/site/"},
            "license": f"{REPO_URL}/blob/main/LICENSE",
        },
        {
            "@context": "https://schema.org",
            "@type": "BreadcrumbList",
            "itemListElement": [
                {"@type": "ListItem", "position": 1, "name": "AI Visual Prompt Cookbook", "item": f"{BASE_URL}/site/"},
                {"@type": "ListItem", "position": 2, "name": style["category"], "item": f"{BASE_URL}/site/?category={style['category'].replace(' ', '+')}"},
                {"@type": "ListItem", "position": 3, "name": style["name"], "item": url},
            ],
        },
    ]
    # "</" inside a script block would end it early.
    return json.dumps(data, ensure_ascii=False, indent=2).replace("</", "<\\/")


def related_for(style: dict[str, Any], styles: list[dict[str, Any]], limit: int = 6) -> list[dict[str, Any]]:
    same = [s for s in styles if s["category"] == style["category"] and s["slug"] != style["slug"]]
    if len(same) <= limit:
        return same
    # Rotate through the category so neighbours differ from page to page.
    start = [s["slug"] for s in styles if s["category"] == style["category"]].index(style["slug"])
    return [same[(start + i) % len(same)] for i in range(limit)]


def case_label(name: str) -> str:
    if re.fullmatch(r"[a-z0-9]+(-[a-z0-9]+)+", name):
        return " ".join(part.capitalize() for part in name.split("-"))
    return name


def samples_block(style: dict[str, Any]) -> str:
    samples = style.get("samples") or []
    if len(samples) < 2:
        return ""
    examples = json.loads(style["jsonText"]).get("examples") or []
    figures = []
    for sample in samples:
        item = examples[sample["index"]] if sample["index"] < len(examples) else {}
        label = case_label(str(item.get("case_name") or f"Example {sample['index'] + 1}"))
        src = "../../" + sample["img16"]  # data paths are relative to site/
        figures.append(
            f"""          <figure>
            <img src="{esc(src)}" alt="{esc(style['name'])} — example: {esc(label)}" loading="lazy" width="800" height="450">
            <figcaption>{esc(label)}</figcaption>
          </figure>"""
        )
    return f"""
      <section class="sp-cases" aria-label="Example cases">
        <h2>{len(samples)} example cases</h2>
        <p>Same style.json, different subjects. Each case's values are in the <code>examples</code> section of the JSON.</p>
        <div class="sp-case-grid">
{chr(10).join(figures)}
        </div>
      </section>
"""


